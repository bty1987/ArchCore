"""install_config.py — 生成单机部署的两件密钥配置(P0 #8)。

由 install.bat 调用;已存在的文件一律跳过不覆盖(重复安装安全)。

  python scripts/install_config.py --collector-token HEX --wxid WXID [--bootstrap-pw PW]

产出(仓库根相对):
  start-server.bat        服务端启动(含 ARCHCORE_* 密钥环境变量,不入 git)
  collector/config.yaml   采集端配置(source.type=wechat4 主轨,不入 git)
"""

from __future__ import annotations

import argparse
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

START_SERVER_TEMPLATE = """@echo off
rem ArchCore server launcher (generated by install.bat; secrets inside, NOT in git).
rem Close this window to stop the server.
cd /d "%~dp0server"
set ARCHCORE_DB_URL=sqlite:///%~dp0data/archcore.db
set ARCHCORE_MEDIA_DIR=%~dp0data/media
set ARCHCORE_JWT_SECRET={jwt}
set ARCHCORE_COLLECTOR_TOKEN={token}
set ARCHCORE_COLLECTOR_WXID={wxid}
set ARCHCORE_ADMIN_BOOTSTRAP_PASSWORD={bootstrap}
"%~dp0.venv\\Scripts\\python.exe" -m alembic upgrade head
"%~dp0.venv\\Scripts\\python.exe" -m uvicorn archcore_server.main:app --host 127.0.0.1 --port 8000
"""

COLLECTOR_CONFIG_TEMPLATE = """# ArchCore collector config (generated by install.bat; token inside, NOT in git).
# source.type=wechat4 is the 4.x main track: decrypted plain DBs from scripts/decrypt_wechat4.py.
server_base_url: http://127.0.0.1:8000
server_ingest_token: {token}
collector_wxid: "{wxid}"

state_db: ./data/collector_state.db

source:
  type: wechat4
  db_dir: ./data/wechat4_plain/{wxid}
  fixture_path: ./data/fixture_wechat.db

whitelist:                 # F1-6 compliance boundary: non-whitelisted sessions never leave the WeChat dir
  allow_all: false         # personal local testing only; FORBIDDEN in commercial delivery
  groups: []
  group_name_patterns: []
  allow_dm: true

schedule:
  incr_minutes: 60
  flush_seconds: 30

wcf_enabled: false
send_enabled: false        # permanently false: archive system never sends
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--collector-token", default=secrets.token_hex(16))
    ap.add_argument("--wxid", required=True)
    ap.add_argument("--bootstrap-pw", default="")
    args = ap.parse_args()
    bootstrap = args.bootstrap_pw or ("arch" + secrets.token_hex(5))

    ss = ROOT / "start-server.bat"
    if ss.exists():
        print(f"[install] keep existing {ss.name}")
    else:
        ss.write_text(
            START_SERVER_TEMPLATE.format(
                jwt=secrets.token_hex(32), token=args.collector_token,
                wxid=args.wxid, bootstrap=bootstrap,
            ),
            encoding="gbk",  # bat 中文环境安全;内容全 ASCII
        )
        print(f"[install] wrote {ss.name}  (bootstrap admin password: {bootstrap})")

    cfg = ROOT / "collector" / "config.yaml"
    if cfg.exists():
        print(f"[install] keep existing {cfg.parent.name}/{cfg.name}")
    else:
        cfg.write_text(
            COLLECTOR_CONFIG_TEMPLATE.format(token=args.collector_token, wxid=args.wxid),
            encoding="utf-8",
        )
        print(f"[install] wrote collector/config.yaml")

    (ROOT / "data" / "media").mkdir(parents=True, exist_ok=True)


if __name__ == "__main__":
    main()
